// Synthetic agents exercise the real HTTP/UI contract; no AI runner or live task store is used.
import {createRequire} from 'node:module';
import {mkdtemp,mkdir,writeFile,rm} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createStudioServer} from '../server.mjs';
import {queueCommand,queueView} from '../queue.mjs';
const {chromium}=createRequire(import.meta.url)(process.argv[2]||'playwright');
const temp=await mkdtemp(path.join(os.tmpdir(),'studio-agent-ui-')),taskFile=path.join(temp,'tasks.json');
for(const dir of ['Docs','DevLog','Feature/architect','Feature/doc'])await mkdir(path.join(temp,dir),{recursive:true});
const artifact='Feature/architect/2026-09-28_agent-ui-fixture.md';
await writeFile(path.join(temp,'Docs/SprintChangeLog.md'),'## Sprint#4-47 AI 작업 흐름\n- 목표: 독립 테스트\n- 검증: 임시 서버\n');
await writeFile(path.join(temp,artifact),'# 에이전트 UI 검증 산출물\n격리된 테스트 문서입니다.\n');
const server=createStudioServer({root:temp,taskFile});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const command=(action,input)=>queueCommand(taskFile,action,input,{worker:true,root:temp});
const evidence=path.resolve('Feature/doc/evidence/studio-agent-workflow-20260928');
await mkdir(evidence,{recursive:true});
let browser;
try {
  await command('engine',{engine:{status:'ready',message:'격리된 테스트 엔진 준비 완료'}});
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/#schedule`);
  await page.getByRole('heading',{name:'AI 팀이 다음 작업을 기다립니다'}).waitFor();
  const column=status=>page.locator('.column').filter({has:page.locator('.column-head .badge').filter({hasText:new RegExp(`^${status}$`)})});
  const controlClick=async button=>{const response=page.waitForResponse(r=>r.url().endsWith('/api/execution')&&r.request().method()==='POST');await button.click();assert.equal((await response).status(),200);};
  await controlClick(page.getByRole('button',{name:'AI 작업 일시정지'}));
  assert.equal((await queueView(taskFile)).paused,true);
  await controlClick(page.getByRole('button',{name:'AI 작업 재개'}));
  await page.locator('#new-task').click();
  assert.equal(await page.locator('#task-status').isDisabled(),true);
  assert.equal(await page.locator('#task-start-after,#task-auto-run').count(),0);
  await page.locator('#task-title').fill('에이전트 실행 경로 검증');
  await page.locator('#task-date').fill('2099-01-01');
  await page.locator('#save-task').click();await page.locator('#task-dialog').waitFor({state:'hidden'});
  let view=await queueView(taskFile);const taskId=view.ready[0];
  assert.ok(taskId,'Future target dates do not defer execution');
  assert.equal(view.tasks[0].autoRun,true);assert.equal(view.tasks[0].startAfter,'');
  assert.equal(await column('예정').locator('.task-card').count(),1);
  let run=await command('claim',{taskId});
  await command('engine',{engine:{status:'busy',message:'역할별 에이전트 작업 진행'}});
  await page.getByText('요구사항 검토',{exact:true}).waitFor();
  assert.equal(await column('진행 중').locator('.task-card').count(),1);
  await page.locator('.task-card').click();assert.equal(await page.locator('#save-task').isDisabled(),true);
  await controlClick(page.getByRole('button',{name:'중단 요청',exact:true}));
  assert.equal((await queueView(taskFile)).records[taskId].stopRequested,true);
  await command('finish',{taskId,token:run.token,state:'stopped',message:'중단 경로 확인'});
  await page.getByRole('button',{name:'다시 검토',exact:true}).waitFor();
  await controlClick(page.getByRole('button',{name:'다시 검토',exact:true}));
  await page.locator('.close-dialog').first().click();
  run=await command('claim',{taskId});
  const agent=async(role,state,title)=>command('agent',{taskId,token:run.token,agent:{id:role,role,state,title,summary:role==='reviewer'?'독립 검토 <태그>':'역할별 작업 기록',startedAt:new Date().toISOString()}});
  await command('plan',{taskId,token:run.token,plan:{summary:'설계 후 구현하고 독립 검증합니다.',packets:[]}});
  await agent('planner','completed','범위와 완료 조건 정리');
  await agent('implementer','running','기능 구현');
  await command('progress',{taskId,token:run.token,state:'running',message:'구현 담당 진행 중'});
  await page.getByText('개발 중',{exact:true}).waitFor();
  assert.equal(await column('진행 중').locator('.task-card').count(),1);
  await page.locator('.task-card').click();await page.locator('.agent-row.is-running').getByText('구현',{exact:true}).waitFor();
  assert.match(await page.locator('#task-execution').textContent(),/설계 후 구현하고 독립 검증/);
  await page.locator('.close-dialog').first().click();
  await agent('implementer','completed','기능 구현');await agent('builder','completed','빌드 및 동작 검증');await agent('reviewer','running','독립 품질 검토');
  await command('progress',{taskId,token:run.token,state:'verifying',message:'독립 리뷰 단계'});
  await page.getByText('검증 중',{exact:true}).waitFor();
  assert.equal(await column('검증 대기').locator('.task-card').count(),1);
  await page.screenshot({path:path.join(evidence,'agents-verifying-desktop.png'),fullPage:true});
  await page.locator('.task-card').click();await page.locator('.agent-row.is-running').getByText('독립 리뷰',{exact:true}).waitFor();
  assert.match(await page.locator('#task-execution').textContent(),/독립 검토 <태그>/);
  await page.locator('.agent-roster').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(evidence,'agent-role-detail.png'),fullPage:true});
  await page.locator('.close-dialog').first().click();
  await agent('reviewer','completed','독립 품질 검토');await agent('writer','completed','결과 문서 작성');
  await command('finish',{taskId,token:run.token,state:'completed',message:'검증과 문서화 완료',validation:'브라우저 상태 전달 검증',artifacts:[artifact]});
  await command('engine',{engine:{status:'ready',message:'다음 작업 대기'}});
  await page.getByText('실행 완료',{exact:true}).waitFor();
  assert.equal(await column('완료').locator('.task-card').count(),1);
  await page.locator('.task-card').click();
  assert.match(await page.locator('#task-execution').textContent(),/브라우저 상태 전달 검증/);
  assert.equal(await page.locator('.agent-row').count(),5);
  const beforeOpen=(await queueView(taskFile)).taskRevision;
  await page.locator('#task-execution [data-doc]').click();await page.locator('#document-dialog').waitFor();
  assert.equal(await page.locator('#task-dialog').isVisible(),true);
  assert.equal((await queueView(taskFile)).taskRevision,beforeOpen);
  await page.locator('.close-document').click();await page.locator('.close-dialog').first().click();
  await page.locator('#toast').waitFor({state:'hidden'});
  await page.screenshot({path:path.join(evidence,'agents-completed-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(evidence,'agents-mobile.png'),fullPage:true});
  await command('engine',{engine:{status:'blocked',message:'테스트 확인 필요'}});
  await page.getByRole('heading',{name:'AI 실행을 위해 확인이 필요합니다'}).waitFor();
  await command('engine',{engine:{status:'offline',message:'테스트 엔진 오프라인'}});
  await page.getByRole('heading',{name:'AI 실행 엔진 연결 대기'}).waitFor();
  await page.route('**/api/execution',route=>route.abort());
  await page.locator('#error').waitFor();assert.match(await page.locator('#error').textContent(),/마지막 수신 상태/);
  await page.unroute('**/api/execution');await page.locator('#error').waitFor({state:'hidden'});
  assert.deepEqual(errors,[]);
  console.log('PASS: immediate intake despite future deadline, AI-managed status, role cards, plan, progress -> verification -> completion, pause/resume, stop/retry, artifacts, mobile, engine states and disconnect recovery. Isolated synthetic agents only.');
} finally {
  if(browser)await browser.close();await new Promise(resolve=>server.close(resolve));
  assert.equal(path.dirname(path.resolve(temp)),path.resolve(os.tmpdir()));
  assert.ok(path.basename(temp).startsWith('studio-agent-ui-'));await rm(temp,{recursive:true,force:true});
}
